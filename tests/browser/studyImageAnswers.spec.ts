import { expect, test } from '@playwright/test'

test('shows all nonempty answer columns in order with readable text and ordinary scrolling', async ({ page }, testInfo) => {
  await page.route('**/src/previewFixtures.ts', async route => {
    const response = await route.fetch()
    const body = (await response.text()).replace('"Zusatzinformation"', JSON.stringify('Visible additional information. '.repeat(100)) + ', "Last additional column."')
    await route.fulfill({ response, body })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Study', exact: true }).click()
  const card = page.locator('.flip-card[data-card-id="bird-long"]')
  await card.click()
  await expect.poll(() => card.locator('.flip-card-inner').evaluate(node => getComputedStyle(node).transform)).toMatch(/^matrix3d\(-1,/)
  const back = card.locator('.flip-card-back')
  await expect(back.locator('img')).toHaveCount(0)
  const parts = back.locator('.card-answer-part')
  await expect(parts).toHaveCount(4)
  const note = parts.nth(2)
  expect(await note.evaluate(node => node.getBoundingClientRect().top < node.closest('.card-content-viewport')!.getBoundingClientRect().bottom)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('uniform-image-answer.png') })
  const viewport = back.locator('.card-content-viewport')
  await viewport.evaluate(node => { node.scrollTop = node.scrollHeight })
  await expect(parts.last()).toContainText('Last additional column.')
  expect(await parts.last().evaluate(node => node.getBoundingClientRect().bottom <= node.closest('.card-content-viewport')!.getBoundingClientRect().bottom + 1)).toBe(true)
  const empty = page.locator('.flip-card[data-card-id="bird-empty"]')
  expect(await empty.locator('.card-answer-part').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-column-index')))).toEqual(['1', '2'])
})
